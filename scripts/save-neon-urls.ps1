# Saves the Neon connection strings to .env.neon, which is gitignored.
#
#   powershell -ExecutionPolicy Bypass -File scripts/save-neon-urls.ps1
#
# Neon gives you two strings: the direct one and the pooled one. The pooled one
# is what the deployed app uses, the direct one is for running migrations once.

$ErrorActionPreference = "Stop"
$target = Join-Path (Split-Path -Parent $PSScriptRoot) ".env.neon"

function Ask-Url([string]$label, [string]$hint) {
    Write-Host ""
    Write-Host $label -ForegroundColor Cyan
    Write-Host "  $hint" -ForegroundColor DarkGray
    $value = (Read-Host "  paste it here").Trim()
    if (-not $value) { throw "No $label given." }
    if ($value -notmatch '^(postgresql|postgres)://') {
        throw "That does not look like a PostgreSQL connection string (it should start with postgresql://)."
    }
    return $value
}

$direct = Ask-Url "1. Neon DIRECT connection string" "the one WITHOUT -pooler in the host name"
$pooled = Ask-Url "2. Neon POOLED connection string" "the one WITH -pooler in the host name"

Write-Host ""
Write-Host "Checking what you pasted..." -ForegroundColor Cyan

if ($direct -eq $pooled) {
    Write-Warning "Both strings are identical, so one of them is probably the wrong copy."
} else {
    $directIsPooler = $direct -match '\-pooler\.'
    $pooledIsPooler = $pooled -match '\-pooler\.'
    if ($directIsPooler) { Write-Warning "The DIRECT string contains -pooler, so it may be the pooled one." }
    if (-not $pooledIsPooler) { Write-Warning "The POOLED string has no -pooler in it, so it may be the direct one." }
    if (-not $directIsPooler -and $pooledIsPooler) { Write-Host "  Looks right: direct without -pooler, pooled with -pooler." -ForegroundColor Green }
}

# Keep the password out of the console output.
$mask = { param($url) if ($url -match '://([^:]+):([^@]+)@') { $url -replace '://([^:]+):([^@]+)@', "://`$1:***@" } else { $url } }

$lines = @(
    "# Neon production database. Gitignored, never commit this.",
    "# Generated by scripts/save-neon-urls.ps1",
    "",
    "# Used by the deployed app. The pooled endpoint handles many short connections.",
    "DATABASE_URL=""$pooled""",
    "",
    "# Only for running migrations by hand: npm run db:deploy",
    "DIRECT_DATABASE_URL=""$direct"""
)
Set-Content -Path $target -Value $lines -Encoding utf8

Write-Host ""
Write-Host "Saved to $target" -ForegroundColor Green
Write-Host "  DATABASE_URL        = $(& $mask $pooled)"
Write-Host "  DIRECT_DATABASE_URL = $(& $mask $direct)"
Write-Host ""
Write-Host "Next: migrations and the import can be run against it." -ForegroundColor Cyan